document.addEventListener(
  "DOMContentLoaded",
  function() {
    const form = document.getElementById(
      "addStaffForm"
    );
    if (!form) return;

    form.addEventListener(
      "submit",
      async function(e) {
        e.preventDefault();
        
        const fd = new FormData(this);
        const data = Object.fromEntries(
          fd.entries()
        );
        
        const tokenEl = document.querySelector(
          'input[name="csrf_token"]'
        );
        const token = tokenEl ? 
          tokenEl.value : "";

        try {
          const res = await fetch(
            "/supplier/permissions/api/staff",
            {
              method: "POST",
              headers: {
                "Content-Type": "application/json",
                "X-CSRFToken": token
              },
              body: JSON.stringify(data)
            }
          );

          const result = await res.json();

          if (res.ok && result.success) {
            const modalEl = document.getElementById(
              "addStaffModal"
            );
            const modal = 
              bootstrap.Modal.getInstance(
                modalEl
              );
            if (modal) modal.hide();
            
            form.reset();

            document.getElementById(
              "credName"
            ).textContent = 
              result.staff.name || data.name;
              
            document.getElementById(
              "credUsername"
            ).textContent = 
              result.username || data.username;
              
            document.getElementById(
              "credPassword"
            ).textContent = 
              result.password || "";

            const credModal = 
              new bootstrap.Modal(
                document.getElementById(
                  "credentialsModal"
                )
              );
            credModal.show();
          } else {
            alert(
              result.message || 
              "حدث خطأ أثناء الإضافة"
            );
          }
        } catch (err) {
          console.error(err);
          alert("تعذر الاتصال بالسيرفر");
        }
      }
    );
  }
);

async function resetStaffPassword(id) {
  if (!confirm("إعادة التعيين؟")) return;
  const res = await fetch(
    `/supplier/permissions/api/staff/${id}/reset-password`,
    { method: "POST" }
  );
  const r = await res.json();
  if (res.ok && r.success) {
    alert("كلمة المرور الجديدة: " + r.password);
  }
}

async function toggleStaffActive(id) {
  const res = await fetch(
    `/supplier/permissions/api/staff/${id}/toggle-status`,
    { method: "POST" }
  );
  if (res.ok) location.reload();
}

async function deleteStaff(id) {
  if (!confirm("حذف نهائي؟")) return;
  const res = await fetch(
    `/supplier/permissions/api/staff/${id}/delete`,
    { method: "POST" }
  );
  if (res.ok) {
    document.getElementById(`staff-row-${id}`)?.remove();
  }
}

function openPermissionsModal(id, name) {
  document.getElementById("permStaffId").value = id;
  document.getElementById("permStaffName").textContent = name;
  const m = document.getElementById("permissionsModal");
  if (m) new bootstrap.Modal(m).show();
}