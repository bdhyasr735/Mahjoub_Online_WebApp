document.addEventListener('DOMContentLoaded', function() {
    const form = document.getElementById('addStaffForm');
    if (!form) return;

    form.addEventListener('submit', async function(e) {
        e.preventDefault();
        
        const fd = new FormData(this);
        const data = Object.fromEntries(fd.entries());
        const token = document.querySelector('input[name="csrf_token"]')?.value || '';

        try {
            const res = await fetch('/supplier/permissions/api/staff', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-CSRFToken': token
                },
                body: JSON.stringify(data)
            });

            const result = await res.json();

            if (res.ok && result.success) {
                bootstrap.Modal.getInstance(document.getElementById('addStaffModal'))?.hide();
                form.reset();

                document.getElementById('credName').textContent = result.staff?.name || data.name;
                document.getElementById('credUsername').textContent = result.username || data.username;
                document.getElementById('credPassword').textContent = result.password || '';

                new bootstrap.Modal(document.getElementById('credentialsModal')).show();
            } else {
                alert(result.message || 'خطأ في الحفظ');
            }
        } catch (err) {
            console.error(err);
            alert('خطأ في الاتصال');
        }
    });
});

async function resetStaffPassword(id) {
    if (!confirm('تأكيد إعادة التعيين؟')) return;
    const res = await fetch(`/supplier/permissions/api/staff/${id}/reset-password`, { method: 'POST' });
    const r = await res.json();
    if (res.ok && r.success) {
        alert('كلمة المرور المؤقتة: ' + r.password);
    } else {
        alert(r.message || 'فشل التعيين');
    }
}

async function toggleStaffActive(id) {
    const res = await fetch(`/supplier/permissions/api/staff/${id}/toggle-status`, { method: 'POST' });
    if (res.ok) location.reload();
}

async function deleteStaff(id) {
    if (!confirm('تأكيد الحذف؟')) return;
    const res = await fetch(`/supplier/permissions/api/staff/${id}/delete`, { method: 'POST' });
    if (res.ok) {
        document.getElementById(`staff-row-${id}`)?.remove();
    } else {
        alert('فشل الحذف');
    }
}

function openPermissionsModal(id, name) {
    document.getElementById('permStaffId').value = id;
    document.getElementById('permStaffName').textContent = name;
    const m = document.getElementById('permissionsModal');
    if (m) new bootstrap.Modal(m).show();
}
